// 1. Function Declaration
function greet1() {
document.write("1. Hello, Welcome!<br>");
}
// 2. Function Definition (Function Expression)
let greet2 = function() {
document.write("2. Hello, Good Morning!<br>");
};
// 3. Arrow Function
let greet3 = () => {
document.write("3. Hello, Have a Nice Day!<br>");
};
// Function Calls
greet1();
greet2();
greet3();
